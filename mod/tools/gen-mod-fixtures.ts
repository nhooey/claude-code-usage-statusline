// Write mod/mod-tests/fixtures.gen.ts: the fixture transcripts the mod's
// harness tests read, as data.
//
//   node mod/tools/gen-mod-fixtures.ts [--check]
//
// A harness test runs in the mod's own runtime, which has no Node and no
// file system but the one the test answers `$.fs` with, so the files it
// answers with are carried in a module: each one's path under /fixtures,
// as the documents name it, and its bytes as base64.  The tracker store
// and the planted calibration are the app-41-63 environment's, written as
// tests/run-cases.py writes them, and the defaults file's text.  --check
// fails if the module is stale;
// test/mod-fixtures.test.ts runs it.
import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

const MOD = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const FIXTURES = path.join(MOD, "..", "tests", "fixtures");
const OUT = path.join(MOD, "mod-tests", "fixtures.gen.ts");

// The transcripts and every file beside them that an agent walk reaches.
const ROOTS = ["transcripts/status/main.jsonl",
  "transcripts/status/agents.jsonl", "transcripts/status/agents",
  "transcripts/cost/09-agents.jsonl", "transcripts/cost/09-agents"];

function walk(rel: string): string[] {
  const p = path.join(FIXTURES, rel);
  if (!fs.statSync(p).isDirectory()) return [rel];
  return fs.readdirSync(p).sort()
    .flatMap((n) => walk(path.posix.join(rel, n)));
}

// tests/run-cases.py's TRACKER, as one line.
const TRACKER = '<?xml version="1.0" encoding="UTF-8"?>\n' +
  '<plist version="1.0"><dict>\n' +
  "<key>activeProfileId</key><string>golden</string>\n" +
  '<key>profiles_v3</key><string>[{"id":"golden","claudeUsage":%s}]' +
  "</string>\n</dict></plist>\n";

export function render(): string {
  const env = JSON.parse(fs.readFileSync(
    path.join(FIXTURES, "env", "app-41-63.json"), "utf-8"));
  const files: string[] = [];
  for (const rel of ROOTS.flatMap(walk)) {
    const b64 = fs.readFileSync(path.join(FIXTURES, rel)).toString("base64");
    files.push(`  ${JSON.stringify("/fixtures/" + rel)}:\n` +
      b64.match(/.{1,72}/g)!.map((s) => `    ${JSON.stringify(s)}`)
        .join(" +\n") + ",");
  }
  const tracker = TRACKER.replace("%s", JSON.stringify(env.tracker));
  return [
    "// Generated by mod/tools/gen-mod-fixtures.ts from tests/fixtures/;",
    "// do not edit.",
    "",
    "/** Each fixture file's bytes, base64, by its path under /fixtures. */",
    "export const FILES: { readonly [path: string]: string } = {",
    ...files,
    "}",
    "",
    "/** The app-41-63 environment: its clock, its planted calibration, and",
    " * the tracker store run-cases.py writes for it. */",
    `export const NOW = ${JSON.stringify(env.now)}`,
    `export const CALIB = ${JSON.stringify(env.calib)}`,
    `export const TRACKER = ${JSON.stringify(tracker)}`,
    "",
    "/** The defaults file, mod/defaults/config.jsonc, as the harness's",
    " * `$.fs` answers the mod's read of it. */",
    `export const DEFAULTS_TEXT = ${JSON.stringify(fs.readFileSync(
      path.join(MOD, "defaults", "config.jsonc"), "utf-8"))}`,
    "",
  ].join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = render();
  if (process.argv.includes("--check")) {
    const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf-8") : "";
    if (have !== text) {
      process.stderr.write(OUT + " is stale: run gen-mod-fixtures.ts\n");
      process.exit(1);
    }
  } else {
    fs.mkdirSync(path.dirname(OUT), { recursive: true });
    fs.writeFileSync(OUT, text);
  }
}
